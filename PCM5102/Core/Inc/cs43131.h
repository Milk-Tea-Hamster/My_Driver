#ifndef __CS43131_H__
#define __CS43131_H__

#include "main.h"

/* ============================================================================
 * I2C 引脚配置 (I2C1: PB6=SCL, PB7=SDA)
 * ============================================================================ */
#define CS43131_I2C_HANDLE      hi2c1
#define CS43131_I2C_ADDR        0x60U

/* 硬件复位引脚 (复用 PA1, 如无连接可注释掉 CS43131_RST_PIN) */
#define CS43131_RST_PORT        GPIOA
#define CS43131_RST_PIN         GPIO_PIN_1

/* I2C 超时 (ms) */
#define CS43131_I2C_TIMEOUT     100U

/* ============================================================================
 * 电源域掩码 (寄存器 0x020000, PDN 位: 0=上电 1=掉电)
 * ============================================================================ */
#define CS43131_PWR_XSP         (1U << 7)
#define CS43131_PWR_ASP         (1U << 6)
#define CS43131_PWR_DSDIF       (1U << 5)
#define CS43131_PWR_HP          (1U << 4)
#define CS43131_PWR_XTAL        (1U << 3)
#define CS43131_PWR_PLL         (1U << 2)
#define CS43131_PWR_CLKOUT      (1U << 1)

/* ============================================================================
 * 采样率枚举 (寄存器 0x01000B)
 * ============================================================================ */
typedef enum {
    CS43131_SR_32K   = 0,
    CS43131_SR_44K1  = 1,
    CS43131_SR_48K   = 2,
    CS43131_SR_88K2  = 3,
    CS43131_SR_96K   = 4,
    CS43131_SR_176K4 = 5,
    CS43131_SR_192K  = 6,
    CS43131_SR_352K8 = 7,
    CS43131_SR_384K  = 8,
} CS43131_SampleRate;

/* ============================================================================
 * 位深枚举 (寄存器 0x01000C)
 * ============================================================================ */
typedef enum {
    CS43131_BITS_32 = 0,
    CS43131_BITS_24 = 1,
    CS43131_BITS_16 = 2,
    CS43131_BITS_8  = 3,
} CS43131_BitDepth;

/* ============================================================================
 * API
 * ============================================================================ */

uint8_t CS43131_Init(void);                       /* 完整初始化, 返回 DevID[0], 0=失败 */
void    CS43131_SetVolume(uint8_t vol);            /* 0=0dB, 255=静音 */
void    CS43131_Mute(uint8_t mute);               /* 0=正常, 1=静音 */
void    CS43131_PowerDown(uint8_t pdn);            /* 0=上电, 1=全部掉电 */
void    CS43131_SetSampleRate(CS43131_SampleRate sr);
void    CS43131_SetBitDepth(CS43131_BitDepth bits);
void    CS43131_SetFilter(uint8_t mode);           /* 0=快滚降, 1=慢滚降, 2=低延迟 */

#endif /* __CS43131_H__ */
